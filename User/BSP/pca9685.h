/**
  ******************************************************************************
  * @file    pca9685.h
  * @brief   PCA9685 舵机驱动: 软件模拟 I2C 通信, 16 路 PWM 输出, 频率 50Hz
  ******************************************************************************
  * 引脚定义:
  *   - SCL : PB6 (软件模拟, 开漏输出 + 外部上拉)
  *   - SDA : PB7 (软件模拟, 开漏输出 + 外部上拉)
  *   - 舵机通道 0~6 一一对应 1~7 号药盒的舵机
  * 修改引脚只需改本文件的 I2C_SCL_xxx / I2C_SDA_xxx 宏,
  * 时序与寄存器操作部分(pca9685.c)无需改动。
  *
  * 为什么用软件模拟 I2C 而不是 STM32F103 的硬件 I2C 外设:
  *   该系列硬件 I2C 存在已知稳定性缺陷(总线可能死锁在 BUSY),
  *   长期无人值守的药箱无法承受"通信卡死必须复位"的代价。
  *
  * 电气前提: SCL/SDA 必须有**外部上拉电阻**。开漏输出只能拉低、
  *   不能主动输出高电平, 没有上拉则总线永远读不到高电平。
  ******************************************************************************
  */
#ifndef __PCA9685_H__
#define __PCA9685_H__

#include "stm32f10x.h"

/* 软件 I2C 引脚(如需改引脚改这里) */
/* 说明: 用 GPIO 模拟 I2C, 不用 STM32F103 硬件 I2C 外设
 * (该系列硬件 I2C 有已知稳定性问题), 实现见 pca9685.c */
#define I2C_SCL_PORT   GPIOB
#define I2C_SCL_PIN    GPIO_Pin_6
#define I2C_SDA_PORT   GPIOB
#define I2C_SDA_PIN    GPIO_Pin_7

/* PCA9685 的 7 位 I2C 地址: 模块默认 A0~A5 全部接高, 因此为 0x40。
 * 注意是 7 位地址, 收发时由驱动左移 1 位并补上读写方向位 */
#define PCA9685_ADDR        0x40u

/* PWM 频率(Hz): 舵机标准频率 50Hz, 对应周期 20ms。
 * 由预分频寄存器 0xFE 决定: prescale = 25MHz/(4096*50) - 1 = 121 */
#define PCA9685_FREQ        50u

/* 舵机脉宽计数范围(基于 50Hz + 12 位计数器: 4096 计数 = 20ms, 即 1 计数 ≈ 4.88us)
 *   0.5ms -> 102 计数 -> 舵机 0 度
 *   2.5ms -> 512 计数 -> 舵机 180 度 */
#define SERVO_PULSE_MIN     102u    /* 对应 0.5ms 脉宽, 舵机 0 度(关盖位置) */
#define SERVO_PULSE_MAX     512u    /* 对应 2.5ms 脉宽, 舵机 180 度(最大角度) */

/* 通道号上限: PCA9685 共 16 路, 编号 0~15;
 * 本项目中只有 0~6 接了舵机(对应 1~7 号药盒) */
#define PCA9685_CH_MAX      15u

/* 初始化 PCA9685: 配好软件 I2C 引脚, 设 50Hz PWM, 开自动递增与推挽输出, 最后各路归位 */
void PCA9685_Init(void);

/* 设置指定通道舵机角度: ch=0~15, angle=0~180 度(>180 截断); 成功返回 1 */
uint8_t PCA9685_SetAngle(uint8_t ch, uint8_t angle);

/* 设置指定通道 PWM 起止计数(12 位, 0~4095): ch=0~15; 成功返回 1 */
uint8_t PCA9685_SetPWM(uint8_t ch, uint16_t on, uint16_t off);

/* 全部复位: 通道 0~6 舵机转 0 度(关盖位置), 其余通道关闭输出 */
void PCA9685_ResetAll(void);

#endif /* __PCA9685_H__ */
