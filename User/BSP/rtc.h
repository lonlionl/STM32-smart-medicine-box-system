/**
  ******************************************************************************
  * @file    rtc.h
  * @brief   RTC 实时时钟模块: 32.768kHz 外部晶振走时, 掉电由纽扣电池维持
  ******************************************************************************
  * 说明:
  *   - RTC 计数器里保存的是 **Unix 时间戳(秒)**, 自 1970-01-01 00:00:00 起算,
  *     32 位计数到 2106 年才回绕, 因此比较/相减/调度都只需整数运算;
  *   - 是否已初始化由 BKP 备份寄存器里的魔数判断(备份域由纽扣电池供电,
  *     主电源掉电不丢), 所以普通重启不会把时间清零;
  *   - 提供时间戳与年月日时分秒的互转、星期计算, 是界面显示、定时调度
  *     与 NTP 校时的公共基础;
  *   - 时钟源优先用外部 LSE(PC14/PC15 接 32.768kHz 晶振);
  *     晶振缺失或不起振时自动回退到内部 LSI, 保证仍能走时(精度较差)。
  ******************************************************************************
  */
#ifndef __RTC_H__
#define __RTC_H__

#include "stm32f10x.h"

/* 备份寄存器魔数: 等于此值表示"RTC 已经初始化过"。
 * 备份寄存器由 VBAT 纽扣电池供电, 主电源掉电后值仍然保留,
 * 因此它区分的是"首次装配/换过电池"与"普通重启"两种情况。
 * 选 0xA5A5 只为不像随机值, 无算法含义 */
#define RTC_BKP_MAGIC  0xA5A5u
/* 存放上述魔数的备份寄存器: 用 BKP_DR1; F1 的 BKP 共 10 个 16 位数据寄存器 */
#define RTC_BKP_REG    BKP_DR1

/* 时间结构体: RTC_GetTime 的拆解结果, 供界面显示与定时比较使用
 *
 * 各字段取值范围(注意都是**十进制数值**, 不是 BCD 码):
 *   year    : 完整年份, 如 2026(不是两位的 26)
 *   month   : 1~12
 *   day     : 1~31
 *   hour    : 0~23(24 小时制)
 *   minute  : 0~59
 *   second  : 0~59
 *   weekday : 1=周一 ... 7=周日(ISO 8601 风格, 由天数派生计算, 不单独存储)
 *
 * 注意: year 用 uint16_t 是因为要容纳到 2106 年的完整年份;
 *       其余字段用 uint8_t 足够且省 RAM。
 */
typedef struct
{
    uint16_t year;      /* 完整年份, 如 2026 */
    uint8_t  month;     /* 1 ~ 12 */
    uint8_t  day;       /* 1 ~ 31 */
    uint8_t  hour;      /* 0 ~ 23 */
    uint8_t  minute;    /* 0 ~ 59 */
    uint8_t  second;    /* 0 ~ 59 */
    uint8_t  weekday;   /* 1=周一 ... 7=周日; 派生自时间戳, 非独立存储 */
} RtcTime_t;

/* 初始化 RTC: 首次上电(BKP 无魔数)时配置 LSE/LSI 时钟源并写入默认时间,
   之后上电只恢复走时; 全程依赖纽扣电池保持时间 */
void RTC_Init(void);

/* 获取当前 Unix 时间戳(秒): 自 1970-01-01 00:00:00 起算; 未初始化时返回 0 */
uint32_t RTC_GetEpoch(void);

/* 设置 RTC 时间戳(秒) —— 校时入口(界面手动设置、NTP 同步均调用它),
   内部由 RTC_SetCounter 完成配置模式进出 */
void RTC_SetEpoch(uint32_t epoch);

/* 获取当前日期时间: 把时间戳拆成 年/月/日/时/分/秒/星期 填入 t(7 个字段全部会被写满) */
void RTC_GetTime(RtcTime_t *t);

/* 由年月日时分秒构造 Unix 时间戳(自 1970 起算的秒数);
   参数需自行保证合法, 本函数不做越界校验 */
uint32_t RTC_ToEpoch(uint16_t year, uint8_t month, uint8_t day,
                     uint8_t hour, uint8_t minute, uint8_t second);

#endif /* __RTC_H__ */
