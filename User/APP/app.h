/**
  ******************************************************************************
  * @file    app.h
  * @brief   应用层接口: 药盒状态管理、定时调度、开盒动作协调
  ******************************************************************************
  * 【本模块在系统里的位置】
  *   驱动层(BSP)之上、主循环(main.c)之下, 是"业务逻辑"的唯一去处:
  *     - 定时配置的加载与默认值      (App_Init)
  *     - 每分钟的定时匹配与开盒       (App_Process)
  *     - 一次开盒要做哪些动作         (App_OpenBox)
  *     - 把全部药盒关回去            (App_CloseAllBoxes)
  *     - 云端旧命令的兼容入口         (App_RemoteSetTimer)
  *   界面(menu.c)只负责画和收按键, 云端(mqtt_huawei.c)只负责收发,
  *   真正的"决定做什么"都在 app.c。
  *
  * 【典型调用顺序】
  *   App_Init()  →  主循环 { App_Process(); }
  *   云端命令 → mqtt_huawei.c → App_OpenBox() / App_RemoteSetTimer()
  *   蜂鸣结束或按键停止 → main.c → App_CloseAllBoxes()
  *
  * 【几条必须遵守的约定(与 flash.h / rtc.h 强耦合, 改名请同步)】
  *   1. 药盒编号: 本模块内部统一用 0~6(对应 1~7 号盒),
  *      只在打印日志、界面显示、上报云端时才 +1 换算成人看的编号;
  *   2. 星期下标: 配置数组用 0~6(0=周一), 而 RTC 的 t.weekday 是 1~7, 需减 1;
  *   3. 时间点"未设置"的哨兵是 hour == 0xFF, **不是 0** ——
  *      0 是合法时刻(午夜 0 点), 用 0 当"空"会导致空槽被当成"每天 0 点提醒"
  *      而用户真正设在 0 点的提醒反而静默失效(详见 flash.h 的同名说明);
  *   4. App_OpenBox 只做"发出开盒动作", 硬件上没有盒盖到位检测,
  *      所以 g_BoxState 是软件记录, 不代表盒盖物理上真的打开了。
  ******************************************************************************
  */
#ifndef __APP_H__
#define __APP_H__

#include "stm32f10x.h"

/* ==================== 全局配置(改动会影响 Flash 布局, 见 flash.h) ==================== */
#define BOX_NUM           7u       /* 药盒数量。PCA9685 通道 0~6 与之对应;
                                      也决定 g_Cfg.rules[] 与 g_BoxState[] 的长度 */
#define BOX_MAX_TIMES     4u       /* **每天**最多几个时间点(不是整周)。
                                      决定 BoxRule_t 的第二维: hour[7][BOX_MAX_TIMES] */
#define SERVO_OPEN_ANGLE  90u      /* 开盒时舵机转到的角度(度)。0=关盖, 90=开盖。
                                      改这个值只影响开盒动作, 不改配置结构 */
#define BEEP_SECONDS      60u      /* 开盒后蜂鸣提醒的时长(秒)。到点自动停;
                                      期间按任意键可提前停止并关闭所有药盒 */

/* 药盒状态: 只有"待开启"与"已触发"两态。
   注意语义是"系统已发出开盒动作", 不是"盒盖真的开着"(无到位检测)。 */
typedef enum
{
    BOX_READY  = 0,     /* 待开启: 今天还没触发过 */
    BOX_OPENED = 1      /* 已触发: 已开过盒(界面据此显示"已打开") */
} BoxState_t;

/* 触发方式: 仅用于日志文案与云端上报的区分, 动作本身完全相同 */
typedef enum
{
    TRIG_TIMER  = 0,    /* 定时触发: 由 App_Process 的每分钟匹配命中 */
    TRIG_REMOTE = 1     /* 远程手动触发: 由云端 remote_open_box 命令下发 */
} TrigMode_t;

/* 药盒状态数组: 下标 0~6 对应 1~7 号药盒。
   由 app.c 写入(开盒/关盒/跨天复位), menu.c 读取用于画 7 行状态灯。 */
extern uint8_t g_BoxState[BOX_NUM];

/* 初始化应用层: 从 Flash 读定时配置; 读失败或首次上电则写入默认配置
   (1 号盒 周一 08:00), 并把全部药盒状态复位为待开启。
   必须在 RTC_Init() 之后调用(要用当前时间判断配置是否有效),
   且在 MQTT_Init() 之前(保证云端第一条消息到达前配置已就绪)。 */
void App_Init(void);

/* 主循环周期调用(每轮几毫秒一次), 内部两级节流:
     - 跨天时把 7 个药盒状态复位为待开启;
     - 每分钟只做一次"时:分"匹配, 命中就开盒。
   非阻塞: 不做任何等待, 不调用 Flash 写入。 */
void App_Process(void);

/* 开盒动作: 舵机转到 SERVO_OPEN_ANGLE + 蜂鸣 BEEP_SECONDS 秒
             + 刷新界面 + 上报云端服药记录。
   @param box  药盒下标 0~6(对应 1~7 号盒)
   @param mode 触发方式 TRIG_TIMER / TRIG_REMOTE, 只影响文案与上报内容
   这是"定时触发"与"远程触发"两条链路的唯一汇聚点。 */
void App_OpenBox(uint8_t box, uint8_t mode);

/* 关闭全部药盒: 7 路舵机全部回 0 度、状态复位为待开启、
   并向云端上报 box_num=0(让手机端把界面上的"已打开"标记清掉)。
   触发时机: 蜂鸣自动响完、用户按键停止蜂鸣、或跨天复位。 */
void App_CloseAllBoxes(void);

/* 远程修改定时(旧版 set_schedule 命令的兼容入口)。
   @param box  药盒下标 0~6
   @param day  星期下标 0~6(0=周一)
   @param hour 小时 **0~24**: 1~24 表示 1~24 点(24 归一为 0 点),
               **0 表示清除该天**
   @note 采用"覆盖式"语义: 先清空该盒该天的全部槽位, 再把 hour 写进第 0 个槽位。
         之所以要先清空, 是因为本接口的粒度是"一天一个时间点",
         而本地规则是"一天最多 4 个时间点"; 只写第 0 槽会让旧的第 1~3 个时间点
         继续触发, 用户会以为"改了定时却还在旧时间响"。
         新版做法是整包下发 schedule_1~7(由 mqtt_huawei.c 解析后统一保存),
         本函数保留给旧版客户端与单独调试使用。
   会立即写入 Flash(内部重算 CRC 并回读校验)。 */
void App_RemoteSetTimer(uint8_t box, uint8_t day, uint8_t hour);

#endif /* __APP_H__ */
