/* --------------------------------------------------------------------------
 * HardFault: 硬件错误异常(故障中优先级最高的一类, 它兜住所有没被单独使能的
 * 故障)。常见原因:
 *   - 访问非法地址(空指针、数组越界、外设时钟没使能就去写它的寄存器);
 *   - 除零、非对齐访问、从非法地址取指;
 *   - 栈溢出或栈被写坏(本工程栈 12KB, 但在函数里放大数组仍可能踩坏)。
 * HardFault 一旦发生就"回不去"了 —— 它处于 -1 优先级, 比任何中断都高, 也是
 * 现场调试最常遇到的一类异常。
 *
 * 【现在这种 while(1) 死循环写法的缺点】(以下只是说明, 实现保持 ST 模板不变)
 *   1) 没有任何现场信息: 不读 CFSR / HFSR / BFAR / MMFAR, 也不读异常压栈帧里
 *      的 PC / LR, 于是"死在哪条指令、哪个寄存器异常"完全无从得知, 只能靠猜;
 *   2) 无法自恢复: 死循环既不复位也不喂狗, 设备会一直"假死"到有人断电重启 ——
 *      对需要长期通电、按时提醒吃药的药箱来说是不可接受的;
 *   3) 现象上和"程序还在跑但界面卡住"难以区分, 现场排障成本高;
 *   4) 看门狗也没接: 本工程根本没有使能 IWDG/WWDG(见 stm32f10x_conf.h 注释),
 *      所以连"超时自动复位"这条最后的兜底手段也没有。
 *
 * 【可改进方向】(仅记录, 供后续演进; 本次不改代码)
 *   a) 先存现场再复位/停机, 便于事后分析:
 *        - 故障状态: SCB->CFSR(含 MMFSR/BFSR/UFSR)、SCB->HFSR、
 *          SCB->BFAR(总线错误地址)、SCB->MMFAR(存储器错误地址);
 *        - 出错位置: 从当前 MSP 指向的异常压栈帧里取出 R0~R3/R12/LR/PC/xPSR,
 *          其中 PC 就是"出错的那条指令的地址", 拿到它就能在反汇编里定位;
 *        - 落地方式: printf 打到 USART1, 或写进 RTC 的 BKP 备份寄存器
 *          (掉电不丢), 复位后读出来显示到 LCD 上;
 *   b) 存完现场用 NVIC_SystemReset()(CMSIS 提供)做软件复位以自恢复, 让设备自己
 *      回到可用状态; 复位前可以在 BKP 里累加一个"复位次数", 观察故障频率;
 *   c) 配合独立看门狗 IWDG: 主循环正常运转时定期喂狗, 一旦某处卡死, 看门狗
 *      超时复位, 这才算真正的"自恢复"(注意 IWDG 一旦启动就无法关闭)。
 *   注意: 这四条 Fault 处理函数若真被用到, 说明程序已经出了严重问题, 因此
 *   在量产固件里宁可"记录+复位", 也不要停在死循环里。
 * -------------------------------------------------------------------------- */
void HardFault_Handler(void)
{
    while (1)
    {
    }
}

