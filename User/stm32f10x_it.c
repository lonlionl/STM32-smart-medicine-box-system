/* ============================================================================
 * 模块说明(本项目视角, 补注)
 * ----------------------------------------------------------------------------
 * 项目    : 智能药箱系统
 * 芯片    : STM32F103ZET6 (Cortex-M3, 72MHz), 纯裸机无 RTOS, 主循环轮询
 * 本文件  : stm32f10x_it.c —— 中断与异常服务函数(ISR)的实现文件。
 *           它属于 ST 官方模板, 本次只补中文注释, 代码一字未改。
 *
 * 本文件里"真正会被触发"的其实只有两个:
 *   SysTick_Handler   : 系统 1ms 滴答, 只把毫秒计数加一
 *   USART2_IRQHandler : ESP-01S 串口收数据, 单字节写入 512 字节环形缓冲
 * 其余都是 CPU 内核异常的空实现或死循环实现 —— 它们保留下来, 是因为启动文件
 * startup_stm32f10x_hd.s 的向量表为每个异常都留了入口, 少一个符号链接时就报
 * "undefined symbol"。
 *
 * 关于"中断是怎么进来的": 本文件里没有任何一行"注册中断"的代码。Cortex-M3 的
 * 异常/中断入口是启动文件里那张向量表(本质是一个函数地址数组)。发生中断时,
 * 硬件按异常号去表里取地址并跳转执行。向量表里是 [WEAK] 弱定义, 本文件给出的
 * 强定义会自动覆盖它, 前提是函数名逐字一致(大小写都不能差)。
 * 也就是说: 中断的使能与优先级配置在 usart.c(USART2)和 timer.c(SysTick)里,
 * 而"中断发生后执行什么"全部由本文件决定。
 * ========================================================================== */

#include "stm32f10x_it.h"
#include "timer.h"
#include "usart.h"

/* ==========================================================================
 * 中断服务函数(ISR)的编写原则 —— 本文件所有实现都遵循:
 *   1) 尽量短。ISR 执行期间同级与低优先级中断都被挡住, 长 ISR 会直接影响按键
 *      响应和串口收数。所以这里只做"搬字节和计数", 真正的处理(解析 AT 回应、
 *      判断是否该开门)全部留给主循环;
 *   2) 绝不调用阻塞函数: 不在 ISR 里做延时、等标志位、printf;
 *   3) 与主循环共享的变量要保证"读改写"的原子性。本项目的共享项要么是单字节
 *      标志(uint8_t 的读改写本身就是原子的), 要么是环形缓冲的头/尾下标
 *      (中断只改 head, 主循环只改 tail), 因此天然不需要关中断保护。
 *   本工程堆已被链接器移除(无动态内存分配), 所以 ISR 里也不可能 malloc。
 * ========================================================================== */

/* --------------------------------------------------------------------------
 * SysTick 中断: 系统 1ms 滴答
 * 只调用 Timer_Tick(), 而它内部只做一件事 —— 把毫秒计数 g_TickMs 加一。
 * 为什么"什么都不多做":
 *   - 这个计数是整个软件定时体系的地基(按键消抖 20ms、长按 1500ms、界面每秒
 *     刷新、蜂鸣 60 秒、WiFi/AT 各种超时都靠它), 它必须绝对可靠、绝对短;
 *   - 一旦在这里面顺手加业务逻辑(扫按键、刷屏), 就等于把不确定的开销放到
 *     每秒执行 1000 次的热路径上, 甚至因为调用 LCD 这类慢设备把实时性拖垮;
 *   - 计数是 32 位无符号, 约 49.7 天回绕。所有超时比较都写成
 *     (int32_t)(now - start) >= timeout 的带符号差值形式(见 timer.c), 所以
 *     回绕也不会算错, 这是"用减法代替比较"的经典原因。
 *   - 优先级: timer.c 里把 SysTick 设为最低(0x0F), 免得它抢占外设中断。
 * 因此这是"只记时间、不干活"的典型写法。
 * -------------------------------------------------------------------------- */
void SysTick_Handler(void)
{
    Timer_Tick();
}

/* --------------------------------------------------------------------------
 * USART2 中断: ESP-01S 数据接收
 * 只调用 Usart2_RxIsr(), 它内部做两件事:
 *   1) 收到一个字节(RXNE 置位)就把该字节写进 512 字节环形缓冲
 *      (ESP_RX_BUF_SIZE); 缓冲满了就丢弃这个字节, 而不是阻塞等待 —— 因为
 *      AT 回应是按行解析的, 主循环会周期性把整行取走, 只要平均速率跟得上
 *      就不会丢数据;
 *   2) 检查并清除溢出标志(ORE): 若 CPU 没能及时读走数据, 硬件会置 ORE;
 *      只清 RXNE 不清 ORE 的话, 这个中断会被反复触发, 把主循环彻底饿死。
 *      清 ORE 的唯一办法就是"读一次数据寄存器(DR)", 所以 Usart2_RxIsr 里
 *      特意保留了这一步 —— 少了它, 一次溢出就会导致接收永久卡死。
 *
 * 为什么不在中断里直接解析 AT 回应:
 *   解析要比较整行字符串(几百字节)、还要驱动状态机跳转, 放在每秒上千次级别
 *   的中断上下文里既慢又危险。拆成"中断只管收、主循环负责解析"(生产者/消费者
 *   分工), 是嵌入式里最常用的写法, 也让 ISR 只占几十条指令, 远小于 115200
 *   波特率下一个字节 87us 的间隔, 因此不会漏字节。
 *
 * 硬件连接: PA2=TX / PA3=RX, 115200-8-N-1; 收数用中断, 发送仍用阻塞轮询
 * (发送量小, 阻塞几十微秒可以接受, 没必要再加一条 TXE 中断)。
 * -------------------------------------------------------------------------- */
void USART2_IRQHandler(void)
{
    Usart2_RxIsr();
}

