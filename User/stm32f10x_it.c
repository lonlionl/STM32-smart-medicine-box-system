/* ==========================================================================
 * 补充说明一: 中断优先级分组与本项目的优先级安排
 *   main.c 里执行了 NVIC_PriorityGroupConfig(NVIC_PriorityGroup_2), 含义是
 *   "2 位抢占优先级 + 2 位子优先级"。STM32F1 的 NVIC 每个中断有 4 位优先级,
 *   分组决定了这 4 位怎么切分:
 *     - 抢占优先级(Preemption): 数值小的可以打断数值大的, 即真正意义上的
 *       "嵌套"; 同级抢占之间不能互相打断;
 *     - 子优先级(Sub): 抢占级相同时, 子优先级小的先执行; 但它不能抢占,
 *       只影响"两个中断同时挂起时谁先被响应"。
 *   本项目的实际配置(整体思路: 串口优先, 滴答垫底):
 *     - ESP-01S 串口: 抢占优先级 1、子优先级 0(见 usart.c) —— 相对更高。
 *       理由: 115200 下一个字节只隔 87us, 一旦被别的中断长时间挡住, 数据
 *       寄存器就会被下一个字节覆盖(ORE), 直接表现为"WiFi 突然哑了"。所以
 *       收数中断必须能及时进来;
 *     - SysTick: 优先级 0x0F, 即最低(见 timer.c)。理由: 毫秒计数只是"记时间",
 *       晚几微秒加一毫无影响, 让它垫底可以保证任何外设中断都不会被它延迟。
 *   一句话: 让"会丢数据的"抢占"只会迟到的"。
 *   另外 NVIC_SetPriority(SysTick_IRQn, 0x0F) 写的是"原始优先级值", CMSIS 会
 *   自动按当前分组左移对齐, 不用手工移位。子优先级只在同抢占级之间起作用,
 *   所以上面 USART2 与 SysTick 的差别真正起作用的是抢占优先级 1 vs 3。
 * ========================================================================== */

/* ==========================================================================
 * 补充说明二: 这些函数是怎么被"调用"到的?
 *   本文件里没有一行"注册中断"的代码 —— Cortex-M3 的中断入口是启动文件
 *   startup_stm32f10x_hd.s 里的那张向量表(本质是一个函数地址数组)。
 *   向量表里的名字(如 SysTick_Handler)与本文件里的函数名同名, 链接器就把
 *   向量表的对应位置指向本文件的函数; 名字写错或函数被漏掉, 链接时都会报
 *   "undefined symbol"。
 *   另外, 中断的使能与优先级配置在 usart.c(USART2, 抢占 1/子 0)和
 *   timer.c(SysTick, 0x0F 最低)里 —— 这就是本文件存在的意义:
 *   别人负责"什么时候进中断", 本文件负责"进来之后干什么"。
 * ========================================================================== */

